import { expect, test } from '@playwright/test';
import { ensureUserExists, loginAs } from './_helpers';

for (const width of [390, 1280]) {
  test(`Korean Wegovy pen labels fill inventory and stay separate from injection amounts at ${width}px`, async ({ page }) => {
    const user = 'wegovy-labels-' + width;
    await ensureUserExists(user, 'pwTest123*');
    await page.setViewportSize({ width, height: 840 });
    await loginAs(page, user, 'pwTest123*');
    await page.goto('/injections');
    await page.getByText('위고비 펜 규격·다이얼 안내', { exact: true }).click();
    const table = page.getByRole('table', { name: /국내 위고비 프리필드펜/ });
    await expect(table.getByRole('row')).toHaveCount(6);
    const expected = [['0.25 mg', '1 mg'], ['0.5 mg', '2 mg'], ['1 mg', '4 mg'], ['1.7 mg', '6.8 mg'], ['2.4 mg', '9.6 mg']];
    for (const [index, doses] of expected.entries()) {
      await expect(table.getByRole('row').nth(index + 1).getByRole('cell')).toHaveText(doses);
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: '펜 등록' }).click();
    const selector = page.getByLabel('국내 위고비 4회용 펜 규격');
    const capacity = page.getByLabel('펜 한 개의 표시 총량 (mg)');
    await selector.selectOption({ label: '2.4 mg × 4회분 · 총 9.6 mg' });
    await expect(capacity).toHaveValue('9.6');
    const drug = page.getByRole('combobox', { name: '약물', exact: true });
    await drug.selectOption('tirzepatide');
    await expect(selector).toHaveCount(0);
    await expect(capacity).toHaveValue('');
    await drug.selectOption('semaglutide');
    await selector.selectOption('6800');
    await page.getByLabel('장부 시작 클릭 수 (선택)').fill('47');
    await page.getByLabel('펜 이름').fill('테스트 펜');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    const card = page.getByRole('article', { name: '테스트 펜' });
    await expect(card).toBeVisible();
    await page.reload();
    await expect(card).toContainText('1.7 mg × 4회분');
    await expect(card).toContainText('기록상 잔량 6.8 mg');
    await card.getByRole('button', { name: '투여 기록 추가' }).click();
    await expect(page.getByLabel('실제 투여량 (mg)')).toHaveValue('');
    await expect(selector).toHaveCount(0);
    await page.getByLabel('실제 투여량 (mg)').fill('0.2');
    await page.getByLabel('기록한 사용 클릭 수 (선택)').fill('6');
    await page.getByText('회차별 상태 기록 (선택)', { exact: true }).click();
    await page.getByLabel('주사 부위', { exact: true }).fill('복부 왼쪽');
    await page.getByLabel('당일 체중 (kg)').fill('68.75');
    await page.getByLabel('식욕 억제도', { exact: true }).selectOption('3');
    await page.getByLabel('부작용·컨디션', { exact: true }).fill('오후에 기록한 컨디션');
    await page.getByLabel('식단·운동 등 상세 메모').fill('저녁 산책');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    await expect(card).toContainText('장부상 남은 클릭 41클릭');
    await page.reload();
    await expect(card).toContainText('기록된 사용 6클릭');
    const history = page.locator('#injection-history');
    await expect(history).toContainText('주사 부위 복부 왼쪽');
    await expect(history).toContainText('체중 68.75 kg');
    await expect(history).toContainText('식욕 억제도 3/5점');
    await expect(history).toContainText('오후에 기록한 컨디션');
    await expect(history).toContainText('저녁 산책');
    await expect(page.getByRole('link', { name: /투여 기록/ })).toHaveAttribute('href', '#injection-history');
    await expect(page.getByText('사용 6클릭 · 장부 잔여 41클릭', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: /투여 기록 수정$/ }).click();
    await page.getByLabel('기록한 사용 클릭 수 (선택)').fill('');
    await page.getByText('회차별 상태 기록 (선택)', { exact: true }).click();
    await expect(page.getByLabel('당일 체중 (kg)')).toHaveValue('68.75');
    await page.getByLabel('부작용·컨디션', { exact: true }).fill('');
    await page.getByLabel('식단·운동 등 상세 메모').fill('다시 작성한 메모');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    await expect(card).toContainText('사용 클릭 미입력 1회');
    await expect(card).toContainText('장부상 남은 클릭 —');
    await expect(history).not.toContainText('오후에 기록한 컨디션');
    await expect(history).toContainText('다시 작성한 메모');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  });

  test(`personal workbook example is separate from editable records at ${width}px`, async ({ page }, info) => {
    const user = 'sample-view-' + width;
    await ensureUserExists(user, 'pwTest123*');
    await page.setViewportSize({ width, height: 840 });
    await loginAs(page, user, 'pwTest123*');
    const stamp = { createdAt: '2021-05-10T03:00:00.000Z', updatedAt: '2021-05-10T03:00:00.000Z' };
    const penId = user + '-pen';
    const dates = ['2021-05-02', '2021-05-06', '2021-05-10'];
    const imported = await page.request.post('/api/import', { data: { mode: 'merge', data: {
      injectionPens: [{ ...stamp, id: penId, name: '화면 검증용', drug: 'semaglutide', capacityMcg: 2000, closed: false, isExample: true }],
      injectionEntries: dates.map((d, i) => ({ ...stamp, id: user + '-dose-' + i, penId, amountMcg: (i + 1) * 100, takenAt: d + 'T03:00:00.000Z' })),
    } } });
    expect(imported.ok()).toBe(true);
    await page.goto('/injections');
    await expect(page.getByRole('button', { name: '관리대장 예시' })).toHaveAttribute('aria-pressed', 'true');
    await expect(page.getByRole('article', { name: '화면 검증용' })).toContainText('추정 잔량 1.4 mg');
    await expect(page.getByRole('listitem').filter({ hasText: '2021.05.02' })).toContainText('추정 잔량 1.9 mg');
    await expect(page.getByRole('button', { name: /투여 기록 수정/ })).toHaveCount(0);
    await expect(page.getByRole('img', { name: /위고비 반감기/ })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('main').screenshot({ path: info.outputPath('journal-' + width + '.png') });
    await page.getByLabel('그래프 종류').selectOption('amount');
    await expect(page.getByRole('img', { name: /엑셀 추정 투여량/ })).toBeVisible();
    await page.getByRole('button', { name: '내 기록', exact: true }).click();
    await expect(page.getByRole('button', { name: '펜 등록' })).toBeVisible();
    await expect(page.getByRole('article', { name: '화면 검증용' })).toHaveCount(0);
    expect((await (await page.request.get('/api/injections')).json()).entries).toHaveLength(0);
  });

  test(`injection journal saves, edits, graphs and restores remaining inventory at ${width}px`, async ({ page }) => {
    const user = 'e2e-injections-' + width;
    await ensureUserExists(user, 'pwTest123*');
    await page.setViewportSize({ width, height: 840 });
    await loginAs(page, user, 'pwTest123*');
    await page.goto('/injections');
    await page.getByRole('button', { name: '펜 등록' }).click();
    await page.getByRole('combobox', { name: '약물', exact: true }).selectOption('tirzepatide');
    await page.getByLabel('펜 이름').fill('연습용 기록');
    await page.getByLabel('펜 한 개의 표시 총량 (mg)').fill('5');
    await page.getByRole('button', { name: '저장' }).click();
    const card = page.getByRole('article', { name: '연습용 기록' });
    await card.getByRole('button', { name: '투여 기록 추가' }).click();
    await page.getByRole('spinbutton', { name: '실제 투여량 (mg)', exact: true }).fill('0.125');
    await page.getByRole('button', { name: '저장' }).click();
    await expect(card).toContainText('4.875 mg');
    await page.reload();
    await expect(card).toContainText('4.875 mg');
    await page.getByLabel('그래프 약물').selectOption('tirzepatide');
    await expect(page.getByRole('img', { name: /마운자로 반감기/ })).toBeVisible();
    await page.getByLabel('그래프 종류').selectOption('amount');
    await expect(page.getByRole('img', { name: /마운자로 회차별/ })).toBeVisible();
    await page.getByRole('button', { name: /투여 기록 수정$/ }).click();
    await page.getByRole('spinbutton', { name: '실제 투여량 (mg)', exact: true }).fill('0.25');
    await page.getByRole('button', { name: '저장' }).click();
    await expect(card).toContainText('4.75 mg');
    const journal = await (await page.request.get('/api/injections')).json();
    expect(journal.entries).toHaveLength(1);
    expect(journal.entries[0].amountMcg).toBe(250);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: /투여 기록 수정$/ }).click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: '삭제', exact: true }).click();
    await expect(card).toContainText('기록상 잔량 5 mg');
    await expect(page.getByText('아직 기록한 주사가 없어요.')).toBeVisible();
  });
}
